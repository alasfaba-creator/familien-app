const SAFE_WORDS = ["schwein", "insekt", "insekten", "weintrauben", "weinblätter", "weinstein"];

export function isAlcoholic(name) {
  const n = name.toLowerCase().replace(/ohne alkohol|alkoholfreie?[snmr]?\b/g, " ");
  return n.split(/[^a-zäöüßı]+/).filter(Boolean).some((word) =>
    !SAFE_WORDS.includes(word) &&
    ALCOHOL_WORDS.some((a) => word === a || (a.length >= 4 && (word.endsWith(a) || word.endsWith(a + "e") || word.endsWith(a + "s") || word.startsWith(a + "e"))))
  );
}

export function categoryOf(name) {
  const n = name.toLowerCase();
  for (const [cat, items] of Object.entries(CATALOG)) {
    if (items.some((i) => i.toLowerCase() === n)) return cat;
  }
  return "Sonstiges";
}

export function search(query, limit = 12) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const hits = [];
  for (const [cat, items] of Object.entries(CATALOG)) {
    for (const name of items) {
      const l = name.toLowerCase();
      const idx = l.indexOf(q);
      if (idx >= 0) hits.push({ name, cat, score: idx === 0 ? 0 : 1 });
    }
  }
  const seen = new Set();
  return hits.sort((a, b) => a.score - b.score || a.name.localeCompare(b.name, "de"))
    .filter((h) => !seen.has(h.name) && seen.add(h.name)).slice(0, limit);
}
